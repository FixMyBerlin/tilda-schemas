/**
 * Writes `docs/mapping-targets.md`: every mapping target with its group, category, fixed tags,
 * labels and the plan on a bare way of its own and on a bare road side.
 *
 * Usage: bun run mapping-targets-doc (then `bun run format` in the repo root)
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  MAPPING_TARGET_GROUP_LABELS,
  MAPPING_TARGET_LABELS,
  groupMappingTargets,
  planForMappingTarget,
  type CategoryChangePlan,
  type MappingTarget,
  type OsmTags,
} from '../src/index.ts'

/** The bare way of its own a target is planned on in the table */
function ownWay(target: MappingTarget): OsmTags {
  const id = target.categoryId
  if (id === 'pedestrianAreaBicycleYes') return { highway: 'pedestrian' }
  if (id.startsWith('bicycleRoad')) return { highway: 'residential' }
  if (id.startsWith('footwayBicycleYes')) return { highway: 'footway' }
  if (/^(cycleway_|cyclewayLink$|crossing$|sharedBusLane|cyclewayOnHighwayProtected$)/.test(id))
    return { highway: 'cycleway' }
  return { highway: 'path' }
}

const ROAD: OsmTags = { highway: 'secondary' }

const code = (text: string) => `\`${text}\``

function describePlan(plan: CategoryChangePlan): string {
  if (!plan.aligned) return `– (${plan.conflicts[0]?.code ?? 'not reached'})`
  const entries = [
    ...plan.add.map((e) => code(`${e.key}=${e.value}`)),
    ...plan.change.map((e) => code(`${e.key}=${e.to}`)),
    ...plan.remove.map((key) => `remove ${code(key)}`),
  ]
  return entries.join(' ') || 'nothing to change'
}

function describeFixed(target: MappingTarget): string {
  const entries = Object.entries(target.fixed)
  return entries.length ? entries.map(([k, v]) => code(`${k}=${v}`)).join(' ') : '–'
}

const lines: string[] = [
  '# Mapping targets',
  '',
  '<!-- Generated by `bun run mapping-targets-doc` in packages/bicycle-infrastructure-tagging. Do not edit. -->',
  '',
  'What a mapper picks in a "Change to" select of `@tilda-geo/bicycle-infrastructure-tagging`: a TILDA category (the id of tilda-geo, unchanged) plus the tags the plan must contain. Groups follow the legend "Führungsform einfach" of tilda-geo. See [the tagging package](tagging-package.md#mapping-targets) for how the list is derived.',
  '',
  'The two plan columns show `planForMappingTarget` on a bare way of its own (`highway=path`, or `footway`, `cycleway`, `pedestrian`, `residential` where the category needs it) and on the right side of a bare `highway=secondary`. A dash names the conflict code.',
]

for (const group of groupMappingTargets()) {
  lines.push(
    '',
    `## ${MAPPING_TARGET_GROUP_LABELS.en[group.id]} (${code(group.id)})`,
    '',
    `German legend name: ${MAPPING_TARGET_GROUP_LABELS.de[group.id]}`,
    '',
    '| Id | Category | Fixed tags | Label (de) | Label (en) | Plan on a way of its own | Plan on a road side |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  )
  for (const target of group.targets) {
    const way = ownWay(target)
    const wayPlan = describePlan(planForMappingTarget(way, target.id, 'self'))
    const sidePlan = describePlan(planForMappingTarget(ROAD, target.id, 'right'))
    lines.push(
      `| ${code(target.id)} | ${code(target.categoryId)} | ${describeFixed(target)} | ${MAPPING_TARGET_LABELS.de[target.labelCode]} | ${MAPPING_TARGET_LABELS.en[target.labelCode]} | ${code(`highway=${way.highway}`)}: ${wayPlan} | ${sidePlan} |`,
    )
  }
}

const target = join(dirname(fileURLToPath(import.meta.url)), '../../../docs/mapping-targets.md')
writeFileSync(target, `${lines.join('\n')}\n`)
console.log(`Wrote ${target}`)
