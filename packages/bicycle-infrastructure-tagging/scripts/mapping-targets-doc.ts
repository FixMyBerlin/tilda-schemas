/**
 * Writes `docs/mapping-targets.md`: the kinds with their options, then every mapping choice with
 * its category, tags, label and the plan on a bare way of its own and on a bare road side.
 *
 * Usage: bun run mapping-targets-doc (then `bun run format` in the repo root)
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  MAPPING_OPTION_LABELS,
  MAPPING_TARGET_GROUP_LABELS,
  allMappingChoices,
  groupMappingKinds,
  mappingChoiceLabel,
  mappingChoiceOptions,
  mappingKindLabel,
  planForMappingChoice,
  resolveMappingChoice,
  type CategoryChangePlan,
  type OsmTags,
  type ResolvedMappingChoice,
} from '../src/index.ts'

/** The bare way of its own a target is planned on in the table */
function ownWay(target: ResolvedMappingChoice): OsmTags {
  const id = target.categoryId
  if (id === 'pedestrianAreaBicycleYes') return { highway: 'pedestrian' }
  if (id.startsWith('bicycleRoad')) return { highway: 'residential' }
  if (id.startsWith('footwayBicycleYes')) return { highway: 'footway' }
  if (/^(cycleway_|cyclewayLink$|crossing$|sharedBusLane|cyclewayOnHighwayProtected$)/.test(id))
    return { highway: 'cycleway' }
  return { highway: 'path' }
}

const ROAD: OsmTags = { highway: 'secondary' }

const code = (text: string) => `\`${text}\``

function describePlan(plan: CategoryChangePlan): string {
  if (!plan.aligned) return `– (${plan.conflicts[0]?.code ?? 'not reached'})`
  const entries = [
    ...plan.add.map((e) => code(`${e.key}=${e.value}`)),
    ...plan.change.map((e) => code(`${e.key}=${e.to}`)),
    ...plan.remove.map((key) => `remove ${code(key)}`),
  ]
  return entries.join(' ') || 'nothing to change'
}

function describeFixed(target: ResolvedMappingChoice): string {
  if (target.lifecycle) {
    const tags = Object.entries(target.fixed).map(([k, v]) => code(`${k}=${v}`))
    return [...tags, `lifecycle ${code(target.lifecycle)}`].join(' ')
  }
  const entries = Object.entries(target.fixed)
  return entries.length ? entries.map(([k, v]) => code(`${k}=${v}`)).join(' ') : '–'
}

const words = MAPPING_OPTION_LABELS.en
const listOrDash = (values: string[]) => (values.length ? values.join(', ') : '–')

const lines: string[] = [
  '# Mapping choices',
  '',
  '<!-- Generated by `bun run mapping-targets-doc` in packages/bicycle-infrastructure-tagging. Do not edit. -->',
  '',
  'What a mapper picks in a "Change to" form of `@tilda-geo/bicycle-infrastructure-tagging`: a kind of infrastructure plus options that do not exclude each other (position, signs, lines, state). A choice resolves to one TILDA category (the id of tilda-geo, unchanged), the tags the plan must contain and a lifecycle. Groups follow the legend "Führungsform einfach" of tilda-geo. See [the tagging package](tagging-package.md#mapping-choices) for the rules.',
  '',
  '## Kinds and their options',
  '',
  'Options on a way of its own. On a road side the position is always `adjoining` and there are no two lines. Under construction there is no sign option. "Signs" and "State" always also have "as it is" / "built".',
  '',
  '| Kind | Label (de) | Label (en) | Position | Signs | Lines | State |',
  '| --- | --- | --- | --- | --- | --- | --- |',
]
for (const group of groupMappingKinds()) {
  for (const kind of group.kinds) {
    const options = mappingChoiceOptions({ kind: kind.id })
    const signs = options.sign.map((sign) =>
      sign === 'signed' ? `${sign} (${options.signValue})` : sign,
    )
    lines.push(
      `| ${code(kind.id)} | ${mappingKindLabel(kind.id, 'de')} | ${mappingKindLabel(kind.id, 'en')} | ${listOrDash(options.position)} | ${listOrDash(signs)} | ${listOrDash(options.lines)} | ${listOrDash(options.lifecycle.map((value) => words[value]))} |`,
    )
  }
}

lines.push(
  '',
  'The plan columns below show `planForMappingChoice` on a bare way of its own (`highway=path`, or `footway`, `cycleway`, `pedestrian`, `residential` where the category needs it) and on the right side of a bare `highway=secondary`. A dash names the conflict code; "not offered" means the side has no such option.',
)

const all = allMappingChoices()
for (const group of groupMappingKinds()) {
  lines.push(
    '',
    `## ${MAPPING_TARGET_GROUP_LABELS.en[group.id]} (${code(group.id)})`,
    '',
    `German legend name: ${MAPPING_TARGET_GROUP_LABELS.de[group.id]}`,
    '',
    '| Id | Category | Tags | Label (de) | Plan on a way of its own | Plan on a road side |',
    '| --- | --- | --- | --- | --- | --- |',
  )
  const kinds = new Set(group.kinds.map((kind) => kind.id))
  for (const target of all.filter((choice) => kinds.has(choice.choice.kind))) {
    const way = ownWay(target)
    const wayPlan = describePlan(planForMappingChoice(way, target.choice, 'self'))
    const sidePlan =
      resolveMappingChoice(target.choice, 'right')?.id === target.id
        ? describePlan(planForMappingChoice(ROAD, target.choice, 'right'))
        : 'not offered'
    lines.push(
      `| ${code(target.id)} | ${code(target.categoryId)} | ${describeFixed(target)} | ${mappingChoiceLabel(target.choice, 'de')} | ${code(`highway=${way.highway}`)}: ${wayPlan} | ${sidePlan} |`,
    )
  }
}

const target = join(dirname(fileURLToPath(import.meta.url)), '../../../docs/mapping-targets.md')
writeFileSync(target, `${lines.join('\n')}\n`)
console.log(`Wrote ${target}`)
