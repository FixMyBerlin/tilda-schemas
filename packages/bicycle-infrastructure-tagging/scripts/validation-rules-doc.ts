/**
 * Writes the table of all validation rules into `docs/validation-rules.md`, between the markers
 * `<!-- rules:start -->` and `<!-- rules:end -->`. The rest of the file is written by hand.
 *
 * Usage: bun run validation-rules-doc (then `bun run format` in the repo root)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { MESSAGES, RULES, type RuleSeverity, type RuleSource } from '../src/validations/index.ts'

export const START = '<!-- rules:start -->'
export const END = '<!-- rules:end -->'
export const TARGET = join(
  dirname(fileURLToPath(import.meta.url)),
  '../../../docs/validation-rules.md',
)

const code = (text: string) => `\`${text}\``
const SOURCES: RuleSource[] = ['tilda-geo', 'radnetz']
const SEVERITIES: RuleSeverity[] = ['error', 'warning', 'info']

const count = (source: RuleSource, severity: RuleSeverity) =>
  RULES.filter((rule) => rule.source === source && rule.severity === severity).length

/** The generated lines between the markers (without the markers), as one string */
export function validationRulesDoc(): string {
  const lines: string[] = [
    '<!-- Generated by `bun run validation-rules-doc` in packages/bicycle-infrastructure-tagging. Do not edit. -->',
    '',
    `${RULES.length} rules.`,
    '',
    '| Source | Rules | error | warning | info |',
    '| --- | --- | --- | --- | --- |',
    ...SOURCES.map((source) => {
      const total = RULES.filter((rule) => rule.source === source).length
      return `| ${code(source)} | ${total} | ${SEVERITIES.map((severity) => count(source, severity)).join(' | ')} |`
    }),
  ]

  for (const source of SOURCES) {
    lines.push(
      '',
      source === 'tilda-geo'
        ? '### Source `tilda-geo` (the todos of the processing)'
        : '### Source `radnetz` (profile `radnetz-berlin`)',
      '',
      '| Id | Severity | Applies to | Keys | Message (de) |',
      '| --- | --- | --- | --- | --- |',
    )
    for (const rule of RULES.filter((rule) => rule.source === source)) {
      const message = (MESSAGES.de[rule.message.code] ?? rule.message.code).replaceAll('|', '\\|')
      lines.push(
        `| ${code(rule.id)} | ${rule.severity} | ${rule.appliesTo.join(', ')} | ${rule.keys.map(code).join(' ')} | ${message} |`,
      )
    }
  }
  return lines.join('\n')
}

if (import.meta.main) {
  const doc = readFileSync(TARGET, 'utf8')
  const from = doc.indexOf(START)
  const to = doc.indexOf(END)
  if (from < 0 || to < from) throw new Error(`${TARGET} has no ${START} ... ${END}`)
  writeFileSync(
    TARGET,
    `${doc.slice(0, from + START.length)}\n${validationRulesDoc()}\n${doc.slice(to)}`,
  )
  console.log(`Wrote ${TARGET}`)
}
